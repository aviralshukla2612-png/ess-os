import PDFDocument from "pdfkit";

export interface AttendancePdfReportOptions {
  title: string;
  generatedBy: string;
  dateRange: string;
  summary: {
    totalRecords: number;
    totalHours: number | string;
    totalLate: number;
    department?: string;
  };
  records: Array<{
    employeeName: string;
    employeeCode: string;
    department: string;
    date: string;
    punchIn: string;
    punchOut: string;
    status: string;
    workHours: string;
  }>;
}

export function generateAttendancePdf(options: AttendancePdfReportOptions): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ margin: 40, size: "A4" });
      const buffers: Buffer[] = [];

      doc.on("data", (chunk) => buffers.push(chunk));
      doc.on("end", () => resolve(Buffer.concat(buffers)));
      doc.on("error", (err) => reject(err));

      // Header Banner
      doc.fillColor("#0f172a").rect(0, 0, doc.page.width, 80).fill();

      doc.fillColor("#ffffff").fontSize(20).font("Helvetica-Bold").text("EMPEROR SMART SOLUTIONS", 40, 20);
      doc.fontSize(11).font("Helvetica").fillColor("#94a3b8").text("Official Attendance & Work Hours Report", 40, 45);

      // Report Info
      doc.fillColor("#1e293b").fontSize(14).font("Helvetica-Bold").text(options.title, 40, 100);
      doc.fontSize(9).font("Helvetica").fillColor("#64748b");
      doc.text(`Generated By: ${options.generatedBy} | Date Range: ${options.dateRange} | Printed: ${new Date().toLocaleString("en-IN")}`, 40, 120);

      // KPI Summary Box
      const boxY = 145;
      doc.rect(40, boxY, doc.page.width - 80, 50).fillAndStroke("#f8fafc", "#e2e8f0");

      doc.fontSize(9).font("Helvetica-Bold").fillColor("#475569");
      doc.text("TOTAL LOGGED SHIFTS", 60, boxY + 12);
      doc.text("TOTAL WORK HOURS", 200, boxY + 12);
      doc.text("LATE ARRIVALS", 340, boxY + 12);
      doc.text("DEPARTMENT", 460, boxY + 12);

      doc.fontSize(13).font("Helvetica-Bold").fillColor("#0f172a");
      doc.text(`${options.summary.totalRecords}`, 60, boxY + 28);
      doc.text(`${options.summary.totalHours} hrs`, 200, boxY + 28);
      doc.fillColor(options.summary.totalLate > 0 ? "#dc2626" : "#16a34a").text(`${options.summary.totalLate}`, 340, boxY + 28);
      doc.fillColor("#0f172a").text(options.summary.department || "All Company", 460, boxY + 28);

      // Table Header
      let y = 220;
      doc.rect(40, y, doc.page.width - 80, 24).fill("#0f172a");

      doc.fontSize(8).font("Helvetica-Bold").fillColor("#ffffff");
      doc.text("EMPLOYEE", 45, y + 8);
      doc.text("DEPT", 160, y + 8);
      doc.text("DATE", 230, y + 8);
      doc.text("PUNCH IN", 300, y + 8);
      doc.text("PUNCH OUT", 370, y + 8);
      doc.text("STATUS", 440, y + 8);
      doc.text("HOURS", 500, y + 8);

      y += 24;

      // Table Rows
      doc.font("Helvetica").fontSize(8);
      options.records.slice(0, 50).forEach((rec, i) => {
        if (y > doc.page.height - 60) {
          doc.addPage();
          y = 40;
          // Re-draw table header on new page
          doc.rect(40, y, doc.page.width - 80, 24).fill("#0f172a");
          doc.fontSize(8).font("Helvetica-Bold").fillColor("#ffffff");
          doc.text("EMPLOYEE", 45, y + 8);
          doc.text("DEPT", 160, y + 8);
          doc.text("DATE", 230, y + 8);
          doc.text("PUNCH IN", 300, y + 8);
          doc.text("PUNCH OUT", 370, y + 8);
          doc.text("STATUS", 440, y + 8);
          doc.text("HOURS", 500, y + 8);
          y += 24;
          doc.font("Helvetica").fontSize(8);
        }

        const bg = i % 2 === 0 ? "#ffffff" : "#f8fafc";
        doc.rect(40, y, doc.page.width - 80, 20).fill(bg);

        doc.fillColor("#0f172a").text(`${rec.employeeName} (${rec.employeeCode})`, 45, y + 6, { width: 110, ellipsis: true });
        doc.fillColor("#64748b").text(rec.department, 160, y + 6, { width: 65, ellipsis: true });
        doc.fillColor("#0f172a").text(rec.date, 230, y + 6);
        doc.text(rec.punchIn || "--:--", 300, y + 6);
        doc.text(rec.punchOut || "--:--", 370, y + 6);

        if (rec.status === "LATE") {
          doc.fillColor("#dc2626").text("LATE", 440, y + 6);
        } else {
          doc.fillColor("#16a34a").text(rec.status, 440, y + 6);
        }

        doc.fillColor("#0f172a").text(rec.workHours, 500, y + 6);

        y += 20;
      });

      // Footer
      const totalPages = doc.bufferedPageRange().count;
      for (let p = 0; p < totalPages; p++) {
        doc.switchToPage(p);
        doc.fontSize(8).fillColor("#94a3b8").text(
          `Page ${p + 1} of ${totalPages} — Confidential Emperor Smart Solutions Record — Not for Public Distribution`,
          40,
          doc.page.height - 30,
          { align: "center", width: doc.page.width - 80 }
        );
      }

      doc.end();
    } catch (err) {
      reject(err);
    }
  });
}
